    private void configurarTeclaInicio() {
    getRootPane().getInputMap(JComponent.WHEN_IN_FOCUSED_WINDOW)
            .put(KeyStroke.getKeyStroke("ENTER"), "iniciarJuego");
    getRootPane().getActionMap().put("iniciarJuego", new AbstractAction() {
        @Override
        public void actionPerformed(ActionEvent e) {
            if (panelInicio.isShowing()) {
                mostrarPantallaJuego();
            }
        }
    });
}

    private void actualizarTablaTop() {
    ArrayList<PuntajeJugador> top = panelJuego.getMotor().getTopPuntajes();
    DefaultTableModel modelo = new DefaultTableModel(new Object[]{"#", "Jugador", "Puntaje"}, 0) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };
    int pos = 1;
    for (PuntajeJugador p : top) {
        modelo.addRow(new Object[]{pos++, p.getNombre(), p.getPuntos()});
    }
    tblPuntajes.setModel(modelo);
}

public void mostrarPantallaInicio() {
    actualizarTablaTop();
    cardLayout.show(panelContenedor, "inicio");
}

public void mostrarPantallaJuego() {
    cardLayout.show(panelContenedor, "juego");
    panelJuego.iniciarJuego();
}

public void mostrarPantallaGameOver(int puntaje) {
    lblPuntajeFinal.setText("Puntaje: " + puntaje);
    txtNombreJugador.setText("");
    cardLayout.show(panelContenedor, "gameover");
    txtNombreJugador.requestFocusInWindow();
}
